package services

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"sni-gateway/internal/db"
	"sni-gateway/internal/models"
)

// NginxReloader is implemented by the Docker client to reload nginx via SIGHUP.
type NginxReloader interface {
	KillContainerByComposeService(ctx context.Context, project, service, signal string) error
}

type ConfigGenerator struct {
	NginxConfigDir string
	NginxPID       string
	Reloader       NginxReloader
	ComposeProject string
}

func NewConfigGenerator(configDir, pidFile string, reloader NginxReloader) *ConfigGenerator {
	return &ConfigGenerator{
		NginxConfigDir: configDir,
		NginxPID:       pidFile,
		Reloader:       reloader,
		ComposeProject: "sni-gateway",
	}
}

// generateFiles fetches DB state and returns (streamConfig, httpConfig, error).
func (g *ConfigGenerator) generateFiles() (string, string, error) {
	var rules []models.Rule
	if err := db.DB.Preload("Exit").
		Where("enabled = true").
		Order("priority DESC").
		Find(&rules).Error; err != nil {
		return "", "", err
	}

	var exits []models.Exit
	if err := db.DB.Where("enabled = true").Find(&exits).Error; err != nil {
		return "", "", err
	}

	ts := "# Generated by sni-gateway at " + time.Now().Format(time.RFC3339) + "\n\n"

	streamCfg := ts + buildStreamConfig(rules, exits)
	httpCfg := ts + buildHTTPConfig(rules, exits)

	return streamCfg, httpCfg, nil
}

// Generate returns a combined human-readable preview (used by Preview/Validate API).
func (g *ConfigGenerator) Generate() (string, error) {
	stream, http, err := g.generateFiles()
	if err != nil {
		return "", err
	}
	return "# --- stream context ---\n" + stream + "\n# --- http context ---\n" + http, nil
}

func buildStreamConfig(rules []models.Rule, exits []models.Exit) string {
	var sb strings.Builder

	// No upstream{} blocks — addresses go directly into the map so nginx
	// resolves them via Docker DNS (127.0.0.11) at connect time, not at
	// config-load time. This means stopped exit containers don't break startup.
	sb.WriteString("map $ssl_preread_server_name $tls_backend {\n")
	sb.WriteString("    default 127.0.0.1:10099;\n") // blackhole for unmatched
	for _, line := range buildSNIMap(rules, exits) {
		sb.WriteString("    " + line + "\n")
	}
	sb.WriteString("}\n")

	return sb.String()
}

func buildHTTPConfig(rules []models.Rule, exits []models.Exit) string {
	var sb strings.Builder

	// Same pattern as stream: direct HOST:PORT in the map, resolved at
	// request time via Docker DNS. No upstream{} blocks.
	sb.WriteString("map $http_host $http_backend {\n")
	sb.WriteString("    default 127.0.0.1:10099;\n") // blackhole for unmatched
	for _, line := range buildHTTPMap(rules, exits) {
		sb.WriteString("    " + line + "\n")
	}
	sb.WriteString("}\n")

	return sb.String()
}

// backendAddr returns the HOST:PORT for an exit's relay container.
// nginx resolves the hostname via Docker DNS (127.0.0.11) at connect time.
func backendAddr(e models.Exit) string {
	return fmt.Sprintf("gluetun-%s:%d", e.Name, 10000+int(e.ID))
}

func buildSNIMap(rules []models.Rule, exits []models.Exit) []string {
	exitByID := exitMap(exits)
	var lines []string
	for _, r := range rules {
		if r.ExitID == nil {
			continue
		}
		exit, ok := exitByID[*r.ExitID]
		if !ok {
			continue
		}
		var key string
		if r.Type == "suffix" {
			escaped := regexp.QuoteMeta(r.Pattern)
			key = fmt.Sprintf("~(^|\\.)%s$", escaped)
		} else {
			key = r.Pattern
		}
		lines = append(lines, fmt.Sprintf("%s %s;", key, backendAddr(exit)))
	}
	return lines
}

func buildHTTPMap(rules []models.Rule, exits []models.Exit) []string {
	exitByID := exitMap(exits)
	var lines []string
	for _, r := range rules {
		if r.ExitID == nil {
			continue
		}
		exit, ok := exitByID[*r.ExitID]
		if !ok {
			continue
		}
		var key string
		if r.Type == "suffix" {
			escaped := regexp.QuoteMeta(r.Pattern)
			key = fmt.Sprintf("~(^|\\.)%s$", escaped)
		} else {
			key = r.Pattern
		}
		lines = append(lines, fmt.Sprintf("%s %s;", key, backendAddr(exit)))
	}
	return lines
}

func exitMap(exits []models.Exit) map[uint]models.Exit {
	m := make(map[uint]models.Exit)
	for _, e := range exits {
		m[e.ID] = e
	}
	return m
}

func sanitizeName(name string) string {
	re := regexp.MustCompile(`[^a-zA-Z0-9_]`)
	return re.ReplaceAllString(name, "_")
}

// WriteInitial writes both config files on startup without reloading nginx.
// Ensures sni_stream.conf and sni_http.conf exist before nginx starts.
func (g *ConfigGenerator) WriteInitial() error {
	stream, http, err := g.generateFiles()
	if err != nil {
		return fmt.Errorf("generate initial config: %w", err)
	}
	if err := os.WriteFile(filepath.Join(g.NginxConfigDir, "sni_stream.conf"), []byte(stream), 0644); err != nil {
		return fmt.Errorf("write sni_stream.conf: %w", err)
	}
	if err := os.WriteFile(filepath.Join(g.NginxConfigDir, "sni_http.conf"), []byte(http), 0644); err != nil {
		return fmt.Errorf("write sni_http.conf: %w", err)
	}
	return nil
}

// WriteAndReload writes both config files and signals nginx to reload via SIGHUP.
func (g *ConfigGenerator) WriteAndReload(config string) error {
	stream, http, err := g.generateFiles()
	if err != nil {
		return fmt.Errorf("generate config: %w", err)
	}

	streamFile := filepath.Join(g.NginxConfigDir, "sni_stream.conf")
	httpFile := filepath.Join(g.NginxConfigDir, "sni_http.conf")

	// Backup current files before overwriting
	for _, f := range []string{streamFile, httpFile} {
		if data, readErr := os.ReadFile(f); readErr == nil {
			_ = os.WriteFile(f+".bak", data, 0644)
		}
	}

	if err := os.WriteFile(streamFile, []byte(stream), 0644); err != nil {
		return fmt.Errorf("write sni_stream.conf: %w", err)
	}
	if err := os.WriteFile(httpFile, []byte(http), 0644); err != nil {
		return fmt.Errorf("write sni_http.conf: %w", err)
	}

	// Signal nginx to reload
	if g.Reloader != nil {
		if err := g.Reloader.KillContainerByComposeService(context.Background(), g.ComposeProject, "nginx", "HUP"); err != nil {
			return fmt.Errorf("nginx reload signal: %w", err)
		}
	}

	return nil
}

// Rollback restores both config files from backup and signals nginx to reload.
func (g *ConfigGenerator) Rollback() error {
	streamFile := filepath.Join(g.NginxConfigDir, "sni_stream.conf")
	httpFile := filepath.Join(g.NginxConfigDir, "sni_http.conf")

	for _, f := range []string{streamFile, httpFile} {
		data, err := os.ReadFile(f + ".bak")
		if err != nil {
			return fmt.Errorf("no backup for %s: %w", filepath.Base(f), err)
		}
		if err := os.WriteFile(f, data, 0644); err != nil {
			return fmt.Errorf("restore %s: %w", filepath.Base(f), err)
		}
	}

	if g.Reloader != nil {
		if err := g.Reloader.KillContainerByComposeService(context.Background(), g.ComposeProject, "nginx", "HUP"); err != nil {
			return fmt.Errorf("nginx reload signal: %w", err)
		}
	}

	return nil
}

// Preview returns the combined config string without writing.
func (g *ConfigGenerator) Preview() (string, error) {
	return g.Generate()
}

// WriteHistory records a publish event.
func (g *ConfigGenerator) WriteHistory(version, status, message, config string) {
	history := models.PublishHistory{
		Version: version,
		Status:  status,
		Message: message,
		Config:  config,
	}
	db.DB.Create(&history)
}
